"""Audit the data and write the validation split.

    make splits

Writes:
  data/splits/val_seed0.json       the train/validation split every run reads (decision D2)
  reports/data_inventory.md        counts, duplicates, sequence check, nearest-neighbour audit
  reports/figures/nearest_train_similarity.png
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image

from seg.audit import auc_low_is_positive, image_features, nearest_similarity
from seg.env import get_device
from seg.splits import (
    CLINICDB_SEQUENCE_STARTS,
    clinicdb_sequence,
    list_pairs,
    make_validation_split,
    source_of,
)

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "data"
TRAIN = DATA / "TrainDataset"
TRAIN_IMAGES = TRAIN / "image"  # the archive uses image/, the test folders use images/
TEST = DATA / "TestDataset"
SPLITS = DATA / "splits"
REPORTS = REPO / "reports"

EXPECTED_TRAIN = {"Kvasir": 900, "CVC-ClinicDB": 550}  # PraNet README, decision D1
EXPECTED_TEST = {
    "Kvasir": 100,
    "CVC-ClinicDB": 62,
    "CVC-ColonDB": 380,
    "ETIS-LaribPolypDB": 196,
    "CVC-300": 60,
}
UNSEEN = ("CVC-ColonDB", "ETIS-LaribPolypDB", "CVC-300")


def clinicdb_first(sequence: int) -> int:
    return CLINICDB_SEQUENCE_STARTS[sequence - 1]


def pixel_hash(path: Path) -> str:
    """Hash of decoded pixels, so one image saved twice under different names still matches."""
    img = Image.open(path).convert("RGB")
    return hashlib.sha1(img.tobytes() + str(img.size).encode()).hexdigest()


def png(folder: Path, stems: list[str]) -> list[Path]:
    return [folder / f"{s}.png" for s in stems]


def plot_nearest(groups: dict[str, np.ndarray], out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    names = list(groups)
    fig, ax = plt.subplots(figsize=(9, 0.55 * len(names) + 1.2), dpi=180)
    for i, name in enumerate(names):
        v = groups[name]
        y = len(names) - 1 - i
        jitter = np.random.default_rng(0).uniform(-0.18, 0.18, len(v))
        color = "#eb6834" if name.startswith("Test, CVC-ClinicDB") else "#2a78d6"
        ax.scatter(v, y + jitter, s=5, alpha=0.45, color=color, linewidths=0)
        ax.plot([np.median(v)] * 2, [y - 0.3, y + 0.3], color="#0b0b0b", lw=1.6)
        ax.text(
            1.005,
            y,
            f"median {np.median(v):.3f}",
            va="center",
            fontsize=8,
            color="#52514e",
            transform=ax.get_yaxis_transform(),
        )
    ax.set_yticks(range(len(names)), labels=names[::-1], fontsize=9)
    ax.set_xlabel("similarity to the nearest training image (ResNet-18 features, cosine)", fontsize=9)
    ax.set_xlim(0.4, 1.0)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.tick_params(axis="y", length=0)
    ax.grid(axis="x", color="#e1e0d9", lw=0.8)
    ax.set_axisbelow(True)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out)
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    ok = True
    md = [
        "# Data inventory",
        "",
        "Generated by `scripts/make_splits.py` (`make splits`). Do not edit by hand.",
        "",
    ]

    # 1. counts against the PraNet README
    train = list_pairs(TRAIN_IMAGES, TRAIN / "masks")
    by_src = Counter(source_of(s) for s in train)
    tests = {n: list_pairs(TEST / n / "images", TEST / n / "masks") for n in EXPECTED_TEST}
    md += ["## Counts", "", "| Set | Found | PraNet README |", "|---|---|---|"]
    for src, exp in EXPECTED_TRAIN.items():
        md.append(f"| Train, {src} | {by_src[src]} | {exp} |")
        ok &= by_src[src] == exp
    for n, exp in EXPECTED_TEST.items():
        md.append(f"| Test, {n} | {len(tests[n])} | {exp} |")
        ok &= len(tests[n]) == exp
    md.append("")

    # 2. exact duplicates between training and test
    train_hash = {pixel_hash(p): s for s, p in zip(train, png(TRAIN_IMAGES, train), strict=True)}
    dupes = [
        (n, s, train_hash[h])
        for n, st in tests.items()
        for s in st
        if (h := pixel_hash(TEST / n / "images" / f"{s}.png")) in train_hash
    ]
    md += ["## Exact duplicates between training and test images", ""]
    md += (
        [f"- {n}/{s} is identical to train/{t}" for n, s, t in dupes] or ["None found (pixel-level hash)."]
    ) + [""]

    # 3. features for the audit
    device = get_device()
    feats_train = image_features(png(TRAIN_IMAGES, train), device)
    idx = {s: i for i, s in enumerate(train)}

    # 4. CVC-ClinicDB sequence table, checked against the images
    frames = sorted(int(s) for s in train if source_of(s) == "CVC-ClinicDB")
    fvec = feats_train[[idx[str(f)] for f in frames]]
    consecutive = (fvec[:-1] * fvec[1:]).sum(axis=1)
    crosses = np.array(
        [clinicdb_sequence(a) != clinicdb_sequence(b) for a, b in zip(frames, frames[1:], strict=False)]
    )
    auc = auc_low_is_positive(consecutive, crosses)
    test_frames = [int(s) for s in tests["CVC-ClinicDB"]]
    tr_seq = Counter(clinicdb_sequence(f) for f in frames)
    te_seq = Counter(clinicdb_sequence(f) for f in test_frames)
    shared = sorted(set(tr_seq) & set(te_seq))
    clean = sorted(s for s in tr_seq if s not in te_seq)
    md += [
        "## CVC-ClinicDB video sequences",
        "",
        "The 612 frames come from 29 video sequences. The frame ranges are published with the dataset "
        "(Table 1 on https://polyp.grand-challenge.org/CVCClinicDB/), and are hard-coded in "
        "`seg.splits.CLINICDB_SEQUENCE_STARTS`.",
        "",
        f"- **Check against the images:** similarity of consecutive training frames separates the "
        f"{int(crosses.sum())} sequence boundaries from within-sequence pairs with **AUC {auc:.3f}** "
        f"(boundary median {np.median(consecutive[crosses]):.3f}, within-sequence median "
        f"{np.median(consecutive[~crosses]):.3f}). The table agrees with what the images show.",
        "- **The PraNet CVC-ClinicDB test set shares videos with training:** "
        f"its {len(test_frames)} test frames come from {len(te_seq)} sequences, "
        f"and **{len(shared)}** of those also have training frames. "
        "Its test frames were sampled from the same videos as training frames, so it measures how well "
        "a model handles near-copies of what it trained on, not new patients.",
        f"- Sequences with no test frame at all: {', '.join(map(str, clean))} "
        f"({sum(tr_seq[s] for s in clean)} training frames).",
        "",
    ]

    # 5. validation split: Kvasir by image; CVC-ClinicDB by whole sequence, test-free sequences first
    group_of = {str(f): clinicdb_sequence(f) for f in frames}
    split = make_validation_split(train, group_of, fraction=0.10, seed=args.seed, preferred_groups=set(clean))
    split.meta.update(
        {
            "clinicdb_grouping": "official sequence table (seg.splits.CLINICDB_SEQUENCE_STARTS)",
            "preferred_groups": clean,
            "note": "CVC-ClinicDB validation uses sequences that have no frame in the PraNet test set",
        }
    )
    split.to_json(SPLITS / f"val_seed{args.seed}.json")
    md += [
        "## Validation split",
        "",
        f"Saved to `data/splits/val_seed{args.seed}.json`.",
        "",
        "| Source | Total | 10% target | In validation | Unit |",
        "|---|---|---|---|---|",
    ]
    for src, m in split.meta["sources"].items():
        unit = m["unit"]
        if unit == "sequence":
            unit = f"whole sequences {', '.join(map(str, m['val_groups']))} (no test frames)"
        md.append(f"| {src} | {m['total']} | {m['target']} | {m['val']} | {unit} |")
    md += ["", f"Training: {len(split.train)} images. Validation: {len(split.val)} images.", ""]

    # 6. nearest training image for every evaluation image
    tr_rows = np.array([idx[s] for s in split.train])
    ref = feats_train[tr_rows]
    groups: dict[str, np.ndarray] = {}
    val_k = [s for s in split.val if source_of(s) == "Kvasir"]
    val_c = [s for s in split.val if source_of(s) == "CVC-ClinicDB"]
    groups["Validation, Kvasir"] = nearest_similarity(feats_train[[idx[s] for s in val_k]], ref)
    groups["Validation, CVC-ClinicDB"] = nearest_similarity(feats_train[[idx[s] for s in val_c]], ref)
    for n in EXPECTED_TEST:
        groups[f"Test, {n}"] = nearest_similarity(
            image_features(png(TEST / n / "images", tests[n]), device), ref
        )
    plot_nearest(groups, REPORTS / "figures" / "nearest_train_similarity.png")
    md += [
        "## How close is each evaluation image to the training set",
        "",
        "For every image, the cosine similarity of ResNet-18 features to its most similar training image "
        "(training = the split's training part). Higher means a near-copy of something seen in training.",
        "",
        "| Set | Median | 90th percentile | Share above 0.95 |",
        "|---|---|---|---|",
    ]
    for name, v in groups.items():
        md.append(f"| {name} | {np.median(v):.3f} | {np.quantile(v, 0.9):.3f} | {(v > 0.95).mean():.0%} |")
    md += ["", "![Nearest training image](figures/nearest_train_similarity.png)", ""]

    # near-copies inside Kvasir (independent images in principle, but the dataset has a few)
    names = {"Validation, Kvasir": val_k, "Test, Kvasir": tests["Kvasir"]}
    close = [(g, names[g][i], float(groups[g][i])) for g in names for i in np.flatnonzero(groups[g] > 0.98)]
    md += ["Evaluation images above 0.98, i.e. practically copies of a training image:", ""]
    md += [f"- {g}: `{s}` ({v:.3f})" for g, s, v in close] or ["- none"]
    md.append("")

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "data_inventory.md").write_text("\n".join(md))
    (REPORTS / "data_inventory.json").write_text(
        json.dumps(
            {
                "auc_sequence_table": auc,
                "shared_sequences": shared,
                "clean_sequences": clean,
                "nearest_median": {k: float(np.median(v)) for k, v in groups.items()},
                # per-image values, for the interactive charts on the site
                "nearest": {k: [round(float(x), 4) for x in v] for k, v in groups.items()},
                "clinicdb_sequences": [
                    {
                        "sequence": s,
                        "first_frame": clinicdb_first(s),
                        "train": int(tr_seq.get(s, 0))
                        - (len(m) if s in split.meta["sources"]["CVC-ClinicDB"]["val_groups"] else 0),
                        "val": len(m) if s in split.meta["sources"]["CVC-ClinicDB"]["val_groups"] else 0,
                        "test": int(te_seq.get(s, 0)),
                    }
                    for s in range(1, 30)
                    for m in [[f for f in frames if clinicdb_sequence(f) == s]]
                ],
                "counts": {
                    "train": dict(by_src),
                    "test": {n: len(v) for n, v in tests.items()},
                    "split": {"train": len(split.train), "val": len(split.val)},
                },
                "split": split.meta,
            },
            indent=2,
        )
        + "\n"
    )
    print("\n".join(md))
    if not ok:
        print("\nCOUNTS DO NOT MATCH THE PRANET README", file=sys.stderr)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
